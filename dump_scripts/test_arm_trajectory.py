"""
Tests and visualizes the arm circle trajectory generated by scripts/gen_arm_trajectory.py.

Usage:
    python dump_scripts/test_arm_trajectory.py
    python dump_scripts/test_arm_trajectory.py --skip-viewer
    python dump_scripts/test_arm_trajectory.py --skip-viewer --skip-video
    python dump_scripts/test_arm_trajectory.py --csv src/assets/motions/g1/arm_circle.csv
"""

import math
import time
import numpy as np
import mujoco
import mujoco.viewer

# ---------------------------------------------------------------------------
# Constants
# ---------------------------------------------------------------------------

XML_PATH = "src/assets/robots/unitree_g1/xmls/g1.xml"
EEF_BODY = "right_wrist_yaw_link"

# Circle parameters used by gen_arm_trajectory.py
CIRCLE_CENTER = np.array([0.45, -0.2, 0.9])
CIRCLE_RADIUS = 0.15
CIRCLE_N      = 120       # total waypoints in one loop

# CSV columns 7–35 map to these joints in order
CSV_JOINT_ORDER = [
    # legs (12)
    "left_hip_pitch_joint",   "left_hip_roll_joint",   "left_hip_yaw_joint",
    "left_knee_joint",        "left_ankle_pitch_joint", "left_ankle_roll_joint",
    "right_hip_pitch_joint",  "right_hip_roll_joint",  "right_hip_yaw_joint",
    "right_knee_joint",       "right_ankle_pitch_joint","right_ankle_roll_joint",
    # waist (3)
    "waist_yaw_joint", "waist_roll_joint", "waist_pitch_joint",
    # left arm (7)
    "left_shoulder_pitch_joint", "left_shoulder_roll_joint", "left_shoulder_yaw_joint",
    "left_elbow_joint",
    "left_wrist_roll_joint", "left_wrist_pitch_joint", "left_wrist_yaw_joint",
    # right arm (7)
    "right_shoulder_pitch_joint", "right_shoulder_roll_joint", "right_shoulder_yaw_joint",
    "right_elbow_joint",
    "right_wrist_roll_joint", "right_wrist_pitch_joint", "right_wrist_yaw_joint",
]

# Expected home-pose values (used in test_csv_format)
HOME_HIP_PITCH   = -0.1
HOME_KNEE        =  0.3
HOME_ANKLE_PITCH = -0.2
HOME_SHOULDER_PITCH =  0.35
HOME_ELBOW          =  0.87
HOME_LEFT_SHOULDER_ROLL  =  0.18
HOME_RIGHT_SHOULDER_ROLL = -0.18

# ---------------------------------------------------------------------------
# Inline helper: CSV row → MuJoCo qpos
# ---------------------------------------------------------------------------

def set_qpos_from_csv_row(model, data, row):
    """
    Load a single CSV row into data.qpos and call mj_forward.

    CSV layout:
        col 0–2  : base position xyz
        col 3–6  : base quaternion in xyzw order (MuJoCo stores wxyz)
        col 7–35 : 29 joint angles in CSV_JOINT_ORDER
    """
    data.qpos[0:3] = row[0:3]      # base position
    data.qpos[3]   = row[6]        # quat w  (CSV xyzw → MuJoCo wxyz)
    data.qpos[4]   = row[3]        # quat x
    data.qpos[5]   = row[4]        # quat y
    data.qpos[6]   = row[5]        # quat z
    for i, jname in enumerate(CSV_JOINT_ORDER):
        jid = mujoco.mj_name2id(model, mujoco.mjtObj.mjOBJ_JOINT, jname)
        data.qpos[model.jnt_qposadr[jid]] = row[7 + i]
    mujoco.mj_forward(model, data)


# ---------------------------------------------------------------------------
# Inline helper: scene visualization
# ---------------------------------------------------------------------------

def draw_sphere(scene, pos, size, rgba):
    """Add a sphere geom to the viewer's user scene."""
    if scene.ngeom >= len(scene.geoms):
        return
    g = scene.geoms[scene.ngeom]
    mujoco.mjv_initGeom(
        g,
        mujoco.mjtGeom.mjGEOM_SPHERE,
        np.array([size] * 3),
        np.asarray(pos, dtype=np.float64),
        np.eye(3).flatten(),
        np.array(rgba, dtype=np.float32),
    )
    scene.ngeom += 1


# ---------------------------------------------------------------------------
# Shared loader
# ---------------------------------------------------------------------------

def load_csv(csv_path):
    """Load CSV, returning a float64 numpy array of shape (N, 36)."""
    return np.loadtxt(csv_path, delimiter=",")


def load_model():
    """Return (model, data) for the G1 robot."""
    model = mujoco.MjModel.from_xml_path(XML_PATH)
    data  = mujoco.MjData(model)
    return model, data


# ---------------------------------------------------------------------------
# Test 1 – IK convergence check
# ---------------------------------------------------------------------------

def test_ik_convergence(csv_path):
    """
    For 5 evenly-spaced rows, compare the EEF position obtained from the CSV
    qpos against the ideal circle waypoint at that index.
    Asserts all errors are < 0.05 m (loose IK quality check).
    """
    traj = load_csv(csv_path)
    n_rows = len(traj)
    model, data = load_model()
    eef_id = mujoco.mj_name2id(model, mujoco.mjtObj.mjOBJ_BODY, EEF_BODY)

    indices = np.linspace(0, n_rows - 1, 5, dtype=int)
    errors  = []

    for idx in indices:
        row = traj[idx]
        set_qpos_from_csv_row(model, data, row)
        eef_pos = data.xpos[eef_id].copy()

        # Ideal circle waypoint: circle is in YZ plane (x=constant)
        # matches gen_arm_trajectory.py: center[1]+r*cos(a), center[2]+r*sin(a)
        angle     = idx / CIRCLE_N * 2 * math.pi
        ideal_pos = np.array([
            CIRCLE_CENTER[0],
            CIRCLE_CENTER[1] + CIRCLE_RADIUS * math.cos(angle),
            CIRCLE_CENTER[2] + CIRCLE_RADIUS * math.sin(angle),
        ])
        err = np.linalg.norm(eef_pos - ideal_pos)
        errors.append(err)
        print(f"  row {idx:3d}  eef={eef_pos}  ideal={ideal_pos}  err={err:.4f} m")

    max_err = max(errors)
    print(f"  max error = {max_err:.4f} m  (threshold 0.05 m)")
    assert max_err < 0.05, (
        f"IK quality too low: max position error {max_err:.4f} m >= 0.05 m"
    )


# ---------------------------------------------------------------------------
# Test 2 – CSV format validation
# ---------------------------------------------------------------------------

def test_csv_format(csv_path):
    """
    Validate the shape and expected column statistics of arm_circle.csv.
    - Shape must be (N>=60, 36)
    - Leg columns must be close to HOME_KEYFRAME values
    - Right arm columns must vary across frames (IK is doing something)
    """
    traj = load_csv(csv_path)
    n_rows, n_cols = traj.shape

    # ── shape ──
    assert n_cols == 36, f"Expected 36 columns, got {n_cols}"
    assert n_rows >= 60,  f"Expected at least 60 rows, got {n_rows}"
    print(f"  shape: {traj.shape}  OK")

    # Column index helpers (relative to traj[:,7:])
    # CSV_JOINT_ORDER indices:
    #   0–5   left leg, 6–11 right leg, 12–14 waist
    #   15–21 left arm, 22–28 right arm
    col = lambda name: 7 + CSV_JOINT_ORDER.index(name)

    # ── leg home values ──
    leg_checks = [
        ("left_hip_pitch_joint",   HOME_HIP_PITCH,   0.05),
        ("right_hip_pitch_joint",  HOME_HIP_PITCH,   0.05),
        ("left_knee_joint",        HOME_KNEE,         0.05),
        ("right_knee_joint",       HOME_KNEE,         0.05),
        ("left_ankle_pitch_joint", HOME_ANKLE_PITCH,  0.05),
        ("right_ankle_pitch_joint",HOME_ANKLE_PITCH,  0.05),
    ]
    for jname, expected, tol in leg_checks:
        c = col(jname)
        actual_mean = traj[:, c].mean()
        assert abs(actual_mean - expected) < tol, (
            f"{jname}: mean {actual_mean:.4f} deviates from expected {expected} "
            f"by more than {tol}"
        )

    # ── right arm columns vary ──
    right_arm_cols = [col(j) for j in [
        "right_shoulder_pitch_joint", "right_shoulder_roll_joint",
        "right_shoulder_yaw_joint",   "right_elbow_joint",
        "right_wrist_roll_joint",     "right_wrist_pitch_joint",
        "right_wrist_yaw_joint",
    ]]
    stds = traj[:, right_arm_cols].std(axis=0)
    n_varying = (stds > 0.01).sum()
    assert n_varying >= 3, (
        f"Expected at least 3 right arm joints to vary (std>0.01), got {n_varying}"
    )

    # ── print block summaries ──
    base_block  = traj[:, 0:7]
    leg_block   = traj[:, 7:19]
    waist_block = traj[:, 19:22]
    larm_block  = traj[:, 22:29]
    rarm_block  = traj[:, 29:36]

    for label, block in [
        ("base (cols 0–6)",       base_block),
        ("legs (cols 7–18)",      leg_block),
        ("waist (cols 19–21)",    waist_block),
        ("left arm (cols 22–28)", larm_block),
        ("right arm (cols 29–35)",rarm_block),
    ]:
        print(f"  {label}  min={block.min():.4f}  max={block.max():.4f}  std={block.std():.4f}")

    print(f"  right arm joint stds: {stds.round(4)}")
    print(f"  varying joints (std>0.01): {n_varying} / {len(right_arm_cols)}")


# ---------------------------------------------------------------------------
# Test 3 – Passive viewer replay
# ---------------------------------------------------------------------------

def test_replay_viewer(csv_path):
    """
    Replay the trajectory in an interactive passive viewer at 30 fps.
    Draws a cyan sphere at the EEF and small red spheres for all 120
    circle target waypoints.  Closes after one full loop.
    """
    traj   = load_csv(csv_path)
    model, data = load_model()
    eef_id = mujoco.mj_name2id(model, mujoco.mjtObj.mjOBJ_BODY, EEF_BODY)

    # Precompute all 120 circle target positions (circle in YZ plane, x=constant)
    circle_targets = np.array([
        [
            CIRCLE_CENTER[0],
            CIRCLE_CENTER[1] + CIRCLE_RADIUS * math.cos(i / CIRCLE_N * 2 * math.pi),
            CIRCLE_CENTER[2] + CIRCLE_RADIUS * math.sin(i / CIRCLE_N * 2 * math.pi),
        ]
        for i in range(CIRCLE_N)
    ])

    with mujoco.viewer.launch_passive(model, data) as viewer:
        viewer.sync()
        for row in traj:
            if not viewer.is_running():
                break

            set_qpos_from_csv_row(model, data, row)

            # Draw into user scene
            scn = viewer.user_scn
            assert scn is not None
            scn.ngeom = 0

            # Cyan sphere at current EEF
            draw_sphere(scn, data.xpos[eef_id], 0.025, [0.0, 0.8, 1.0, 1.0])

            # Small red spheres for all circle waypoints
            for tp in circle_targets:
                draw_sphere(scn, tp, 0.008, [1.0, 0.2, 0.2, 0.7])

            viewer.sync()
            time.sleep(1.0 / 30.0)

    print("Replay complete")


# ---------------------------------------------------------------------------
# Test 4 – Offscreen video export
# ---------------------------------------------------------------------------

def test_video_export(csv_path):
    """
    Render each frame offscreen and save to /tmp/arm_circle.mp4 (via imageio)
    or as individual PNGs if imageio is not available.
    """
    traj   = load_csv(csv_path)
    model, data = load_model()

    renderer = mujoco.Renderer(model, height=480, width=640)

    frames = []
    for row in traj:
        set_qpos_from_csv_row(model, data, row)
        renderer.update_scene(data)
        frame = renderer.render()          # returns (H, W, 3) uint8
        frames.append(frame.copy())

    # Try imageio first
    try:
        import imageio
        out_path = "/tmp/arm_circle.mp4"
        imageio.mimwrite(out_path, frames, fps=30)
        print(f"  Video saved to {out_path}")
        return
    except ImportError:
        pass

    # Fall back to PIL
    try:
        from PIL import Image
        for i, frame in enumerate(frames):
            out_path = f"/tmp/arm_circle_frame_{i:04d}.png"
            Image.fromarray(frame).save(out_path)
        print(f"  Frames saved as /tmp/arm_circle_frame_XXXX.png ({len(frames)} files)")
        return
    except ImportError:
        pass

    # Fall back to OpenCV
    try:
        import cv2
        for i, frame in enumerate(frames):
            out_path = f"/tmp/arm_circle_frame_{i:04d}.png"
            cv2.imwrite(out_path, cv2.cvtColor(frame, cv2.COLOR_RGB2BGR))
        print(f"  Frames saved as /tmp/arm_circle_frame_XXXX.png ({len(frames)} files) via cv2")
        return
    except ImportError:
        pass

    print("  WARNING: imageio, Pillow, and cv2 all unavailable — frames not saved.")


